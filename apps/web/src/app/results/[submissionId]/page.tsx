import type { Metadata } from "next";
import Link from "next/link";
import { api } from "@/lib/api-client";
import { PublicChallengeSummary, PublicTally, SubmissionWithOutcome } from "@/lib/types";
import { formatCents } from "@/lib/format";
import { outcomeTone, OUTCOME_COPY } from "@/lib/outcome";
import { tierBadgeStyle, tierLabel } from "@/lib/tier";
import { Avatar } from "@/components/Avatar";
import { Celebration } from "@/components/Celebration";

async function load(submissionId: string) {
  return api.get<SubmissionWithOutcome>(`/submissions/${submissionId}`);
}

export async function generateMetadata({
  params,
}: {
  params: { submissionId: string };
}): Promise<Metadata> {
  const submission = await load(params.submissionId);
  const { headline, tagline } = OUTCOME_COPY[outcomeTone(submission)];
  return {
    title: `${headline} — ${submission.challenge.title} | Perokio`,
    description: tagline,
  };
}

// The actual "share card" surface (growth-viral-mechanics.md §3) — a
// creator posts this link; the unfurl preview IS the card, generated by the
// sibling opengraph-image.tsx from the same status/isWinner data. While the
// entry is still live in the public vote, this doubles as the "entry card"
// with a real vote count and a rally CTA — same route, not a separate one.
export default async function ResultPage({ params }: { params: { submissionId: string } }) {
  const submission = await load(params.submissionId);
  const tone = outcomeTone(submission);
  const { headline, tagline } = OUTCOME_COPY[tone];

  let liveVotes: number | null = null;
  let votingIsLive = false;
  if (tone === "pending" || tone === "advanced") {
    try {
      const summary = await api.get<PublicChallengeSummary>(
        `/public/challenges/${submission.challengeId}`,
      );
      if (summary.currentRound?.type === "public_vote_final" && summary.currentRound.status === "open") {
        const tally = await api.get<PublicTally>(
          `/public/challenges/${submission.challengeId}/tally`,
        );
        if (tally.visible) {
          liveVotes = tally.tallies.find((t) => t.submissionId === submission.id)?.votes ?? 0;
          votingIsLive = true;
        }
      }
    } catch {
      // Public tally not available for this round/challenge yet — fine, just skip the live count.
    }
  }

  return (
    <div>
      <div style={{ display: "flex", alignItems: "center", gap: "0.75rem", position: "relative" }}>
        {tone === "winner" && <Celebration />}
        <Avatar userId={submission.creatorId} size={56} tier={submission.creatorTier} />
        <h1 style={{ margin: 0 }}>{headline}</h1>
      </div>
      <p className="muted">
        {tagline} ·{" "}
        <span className="badge badge-tier" style={tierBadgeStyle(submission.creatorTier) as React.CSSProperties}>
          {tierLabel(submission.creatorTier)}
        </span>
      </p>

      {votingIsLive && (
        <div className="card" style={{ textAlign: "center" }}>
          <p style={{ fontSize: "2.5rem", fontWeight: 800, margin: 0 }}>{liveVotes}</p>
          <p className="muted" style={{ margin: 0 }}>
            votes so far
          </p>
        </div>
      )}

      <div className="card">
        <h2 style={{ marginTop: 0 }}>{submission.challenge.title}</h2>
        <p>Pool: {formatCents(submission.challenge.prizePool)}</p>
        <p className="muted">Phase: {submission.phase}</p>
      </div>

      {votingIsLive ? (
        <Link
          href={`/battle/${submission.challengeId}?rally=${submission.creatorReferralCode}`}
          className="btn"
        >
          Vote for me
        </Link>
      ) : (
        <Link href={`/battle/${submission.challengeId}`} className="btn">
          Watch the battle
        </Link>
      )}
    </div>
  );
}
